/** A language code and its copy, keyed by generated property name. */
export interface NativeIabCopyLanguage {
	language: string;
	values: Record<string, string>;
}

/**
 * Converts an `iab.` key path to the generated property name.
 *
 * @param keyPath - Path under `iab.`, such as `banner.title`.
 * @returns The lowerCamel name, such as `bannerTitle`.
 */
export const propertyName = function propertyName(keyPath: string): string {
	return keyPath
		.split('.')
		.map((part, index) =>
			index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)
		)
		.join('');
};

/** One generated table: its type, keys and output files. */
export interface NativeCopyTable {
	swiftType: string;
	kotlinType: string;
	/** Doc comment for the type, one line. */
	summary: string;
	/** Where the copy comes from, for the file header. */
	source: string;
	/** Generated property name and its key path in the merged translations. */
	keys: readonly (readonly [name: string, keyPath: string])[];
	/** Whether the type carries `format` with ICU plural support. */
	format: boolean;
	swiftOutput: string;
	kotlinOutput: string;
	kotlinResourceOutput: string;
}

