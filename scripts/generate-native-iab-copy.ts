const readPath = function readPath(source: unknown, keyPath: string): unknown {
	let value = source;
	for (const part of keyPath.split('.')) {
		if (typeof value !== 'object' || value === null) {
			return undefined;
		}
		value = (value as Record<string, unknown>)[part];
	}
	return value;
};

/**
 * The built-in translations with each language's native screen labels merged
 * in: IAB labels into `iab.app`, category-mode labels under `native`. The
 * labels live in `native-app-labels.ts`, outside every package entry, so web
 * bundles don't carry them.
 */
export const translationsWithNativeLabels = (): Record<string, unknown> =>
	Object.fromEntries(
		Object.entries(baseTranslations).map(([language, translations]) => [
			language,
			{
				...translations,
				iab: {
					...translations.iab,
					app: { ...translations.iab.app, ...nativeAppLabels[language] },
				},
				native: nativeConsentLabels[language],
			},
		])
	);

/**
 * Reads one table's copy for every built-in language.
 *
 * @param translations - Language code to translation object.
 * @returns Languages sorted by code.
 * @throws {Error} When a language is missing a key or has an empty value.
 */
export const collectNativeIabCopy = function collectNativeIabCopy(
	translations: Record<string, unknown> = translationsWithNativeLabels(),
	table: NativeCopyTable = IAB_TABLE
): NativeIabCopyLanguage[] {
	const missing: string[] = [];
	const languages = Object.keys(translations)
		.sort()
		.map((language) => {
			const values: Record<string, string> = {};
			for (const [name, keyPath] of table.keys) {
				const value = readPath(translations[language], keyPath);
				if (typeof value !== 'string' || value.trim() === '') {
					missing.push(`${language}: ${keyPath}`);
					continue;
				}
				values[name] = value;
			}
			return { language, values };
		});
	if (missing.length > 0) {
		throw new Error(
			`Missing native ${table.swiftType} copy:\n${missing.join('\n')}`
		);
	}
	if (!languages.some(({ language }) => language === FALLBACK_LANGUAGE)) {
		throw new Error(`The fallback language "${FALLBACK_LANGUAGE}" is missing.`);
	}
	return languages;
};

// Invisible and layout characters are escaped so a reviewer can see them
// and no bidi control can reorder the generated source.
const INVISIBLE = /[\p{Cc}\p{Cf}\p{Zl}\p{Zp}]/u;

const hex = (codePoint: number, width: number) =>
	codePoint.toString(16).toUpperCase().padStart(width, '0');

/**
 * Escapes a value as a Swift string literal.
 *
 * @returns A double-quoted Swift literal.
 */
export const swiftString = function swiftString(value: string): string {
	let out = '';
	for (const char of value) {
		const codePoint = char.codePointAt(0) ?? 0;
		if (char === '\\') {
			out += '\\\\';
		} else if (char === '"') {
			out += '\\"';
		} else if (char === '\n') {
			out += '\\n';
		} else if (char === '\r') {
			out += '\\r';
		} else if (char === '\t') {
			out += '\\t';
		} else if (INVISIBLE.test(char)) {
			out += `\\u{${hex(codePoint, 1)}}`;
		} else {
			out += char;
		}
	}
	return `"${out}"`;
};

/**
 * Escapes a value as a Kotlin string literal, including `$` so no value
 * becomes a string template.
 *
 * @returns A double-quoted Kotlin literal.
 */
export const kotlinString = function kotlinString(value: string): string {
	let out = '';
	for (const char of value) {
		if (char === '\\') {
			out += '\\\\';
		} else if (char === '"') {
			out += '\\"';
		} else if (char === '$') {
			out += '\\$';
		} else if (char === '\n') {
			out += '\\n';
		} else if (char === '\r') {
			out += '\\r';
		} else if (char === '\t') {
			out += '\\t';
		} else if (INVISIBLE.test(char)) {
			// Kotlin has no \u{...}; astral characters become surrogate pairs.
			for (let i = 0; i < char.length; i += 1) {
				out += `\\u${hex(char.charCodeAt(i), 4)}`;
			}
		} else {
			out += char;
		}
	}
	return `"${out}"`;
};

// A suffix keeps codes such as `is` and `in` clear of language keywords.
const identifier = (language: string) =>
	`${language.replace(/-(?<letter>[a-z])/gu, (_match, letter: string) =>
		letter.toUpperCase()
	)}Copy`;

/**
 * Renders the Swift source.
 *
 * @param languages - Output of {@link collectNativeIabCopy}.
 */
export const renderSwift = function renderSwift(
	languages: NativeIabCopyLanguage[],
	table: NativeCopyTable = IAB_TABLE
): string {
	const type = table.swiftType;
	const names = table.keys.map(([name]) => name);
	const lines: string[] = [
		`// ${HEADER}`,
		`// Source: ${table.source}`,
		'',
		`/// ${table.summary}`,
		`public struct ${type}: Sendable, Equatable {`,
		'    /// Language code, lowercase, as in `@inth/sdk-translations`.',
		'    public let language: String',
	];
	for (const [name, keyPath] of table.keys) {
		lines.push(`    /// \`${keyPath}\``);
		lines.push(`    public let ${name}: String`);
	}
	lines.push(
		'',
		'    /// Every language code with generated copy, sorted.',
		`    public static let supportedLanguages: [String] = [${languages
			.map(({ language }) => swiftString(language))
			.join(', ')}]`,
		'',
		'    /// Returns the copy for a language code such as `de` or `pt-BR`.',
		'    /// Matching ignores case and tries the full code, then the part',
		`    /// before \`-\`, then falls back to \`${FALLBACK_LANGUAGE}\`.`,
		`    public static func forLanguage(_ code: String) -> ${type} {`,
		'        let normalized = String(code.lowercased().map { $0 == "_" ? "-" : $0 })',
		'        if let copy = byLanguage[normalized] { return copy }',
		'        if let base = normalized.split(separator: "-").first,',
		'           let copy = byLanguage[String(base)] {',
		'            return copy',
		'        }',
		`        return ${identifier(FALLBACK_LANGUAGE)}`,
		'    }'
	);
	if (table.format) {
		lines.push(
			'',
			'    /// Replaces `{name}` tokens in `template` with `values[name]`, and evaluates ICU plural',
			'    /// tokens such as `{count, plural, one {# partner} other {# partners}}` for this language.',
			'    /// Unknown tokens stay as written. Inserted values are not rescanned.',
			'    public func format(_ template: String, _ values: [String: String]) -> String {',
			'        var result = ""',
			'        var rest = template[...]',
			'        while let open = rest.firstIndex(of: "{") {',
			'            guard let close = Self.matchingBrace(rest, from: open) else { break }',
			'            result += rest[..<open]',
			'            let token = rest[rest.index(after: open)..<close]',
			'            if let value = values[String(token)] {',
			'                result += value',
			'            } else if let plural = plural(token, values) {',
			'                result += plural',
			'            } else {',
			'                result += rest[open...close]',
			'            }',
			'            rest = rest[rest.index(after: close)...]',
			'        }',
			'        result += rest',
			'        return result',
			'    }',
			'',
			'    private static func matchingBrace(_ text: Substring, from open: Substring.Index) -> Substring.Index? {',
			'        var depth = 0',
			'        var index = open',
			'        while index < text.endIndex {',
			'            if text[index] == "{" { depth += 1 } else if text[index] == "}" { depth -= 1; if depth == 0 { return index } }',
			'            index = text.index(after: index)',
			'        }',
			'        return nil',
			'    }',
			'',
			"    /// `name, plural, selector {text} ...`, choosing `=N`, then this language's category, then `other`.",
			'    private func plural(_ token: Substring, _ values: [String: String]) -> String? {',
			'        let parts = token.split(separator: ",", maxSplits: 2).map { $0.trimmingCharacters(in: .whitespaces) }',
			'        guard parts.count == 3, parts[1] == "plural", let raw = values[parts[0]], let count = Int(raw) else { return nil }',
			'        var branches: [String: String] = [:]',
			'        var rest = Substring(parts[2])',
			'        while let open = rest.firstIndex(of: "{"), let close = Self.matchingBrace(rest, from: open) {',
			'            branches[rest[..<open].trimmingCharacters(in: .whitespaces)] = String(rest[rest.index(after: open)..<close])',
			'            rest = rest[rest.index(after: close)...]',
			'        }',
			'        guard let chosen = branches["=\\(count)"] ?? branches[Self.pluralCategory(count, language)] ?? branches["other"] else { return nil }',
			'        return format(chosen.replacingOccurrences(of: "#", with: raw), values)',
			'    }',
			'',
			'    /// CLDR integer plural categories for the languages whose copy uses plural tokens.',
			'    static func pluralCategory(_ n: Int, _ language: String) -> String {',
			'        let ten = n % 10, hundred = n % 100',
			'        switch language {',
			'        case "cs", "sk": return n == 1 ? "one" : (2...4).contains(n) ? "few" : "other"',
			'        case "pl": return n == 1 ? "one" : (2...4).contains(ten) && !(12...14).contains(hundred) ? "few" : "many"',
			'        case "ru", "uk", "hr", "sr", "bs":',
			'            if ten == 1 && hundred != 11 { return "one" }',
			'            if (2...4).contains(ten) && !(12...14).contains(hundred) { return "few" }',
			'            return language == "ru" || language == "uk" ? "many" : "other"',
			'        default: return n == 1 ? "one" : "other"',
			'        }',
			'    }'
		);
	}
	lines.push(
		'',
		`    private static let byLanguage: [String: ${type}] = [`,
		...languages.map(
			({ language }) =>
				`        ${swiftString(language)}: ${identifier(language)},`
		),
		'    ]'
	);
	for (const { language, values } of languages) {
		lines.push('', `    private static let ${identifier(language)} = ${type}(`);
		lines.push(`        language: ${swiftString(language)},`);
		names.forEach((name, index) => {
			const comma = index === names.length - 1 ? '' : ',';
			lines.push(`        ${name}: ${swiftString(values[name] ?? '')}${comma}`);
		});
		lines.push('    )');
	}
	lines.push('}', '');
	return lines.join('\n');
};

/**
 * Renders the Kotlin source. English is inline; every other language comes
 * from {@link renderKotlinResource} on first use.
 *
 * @param languages - Output of {@link collectNativeIabCopy}.
 */
export const renderKotlin = function renderKotlin(
	languages: NativeIabCopyLanguage[],
	table: NativeCopyTable = IAB_TABLE
): string {
	const type = table.kotlinType;
	const resourceName = basename(table.kotlinResourceOutput);
	const names = table.keys.map(([name]) => name);
	const fallback = languages.find(
		({ language }) => language === FALLBACK_LANGUAGE
	);
	if (!fallback) {
		throw new Error(`Missing ${FALLBACK_LANGUAGE} ${type} copy.`);
	}
	const lines: string[] = [
		`// ${HEADER}`,
		`// Source: ${table.source}`,
		'',
		'package com.inth.consentui.generated',
		'',
		'import java.util.Locale',
		'import kotlinx.serialization.json.Json',
		'import kotlinx.serialization.json.JsonObject',
		'import kotlinx.serialization.json.JsonPrimitive',
		'',
		`/** ${table.summary} */`,
		`data class ${type}(`,
		'    /** Language code, lowercase, as in `@inth/sdk-translations`. */',
		'    val language: String,',
	];
	for (const [name, keyPath] of table.keys) {
		lines.push(`    /** \`${keyPath}\` */`);
		lines.push(`    val ${name}: String,`);
	}
	lines.push(') {');
	if (table.format) {
		lines.push(
			'    /**',
			'     * Replaces `{name}` tokens in [template] with `values[name]`.',
			'     * Unknown tokens stay as written. Inserted values are not rescanned. ICU plural tokens such as',
			'     * `{count, plural, one {# partner} other {# partners}}` are evaluated for this language.',
			'     */',
			'    fun format(template: String, values: Map<String, String>): String {',
			'        val result = StringBuilder(template.length)',
			'        var index = 0',
			'        while (index < template.length) {',
			"            val open = template.indexOf('{', index)",
			'            if (open < 0) break',
			'            val close = matchingBrace(template, open)',
			'            if (close < 0) break',
			'            result.append(template, index, open)',
			'            val token = template.substring(open + 1, close)',
			'            val value = values[token] ?: plural(token, values)',
			'            if (value != null) result.append(value) else result.append(template, open, close + 1)',
			'            index = close + 1',
			'        }',
			'        result.append(template, index, template.length)',
			'        return result.toString()',
			'    }',
			'',
			'    private fun matchingBrace(text: String, open: Int): Int {',
			'        var depth = 0',
			'        for (i in open until text.length) {',
			"            if (text[i] == '{') depth++ else if (text[i] == '}') { depth--; if (depth == 0) return i }",
			'        }',
			'        return -1',
			'    }',
			'',
			"    /** `name, plural, selector {text} ...`, choosing `=N`, then this language's category, then `other`. */",
			'    private fun plural(token: String, values: Map<String, String>): String? {',
			"        val parts = token.split(',', limit = 3).map { it.trim() }",
			'        if (parts.size != 3 || parts[1] != "plural") return null',
			'        val raw = values[parts[0]] ?: return null',
			'        val count = raw.toIntOrNull() ?: return null',
			'        val branches = mutableMapOf<String, String>()',
			'        var rest = parts[2]',
			'        while (true) {',
			"            val open = rest.indexOf('{')",
			'            if (open < 0) break',
			'            val close = matchingBrace(rest, open)',
			'            if (close < 0) break',
			'            branches[rest.substring(0, open).trim()] = rest.substring(open + 1, close)',
			'            rest = rest.substring(close + 1)',
			'        }',
			'        val chosen = branches["=$count"] ?: branches[pluralCategory(count, language)] ?: branches["other"] ?: return null',
			'        return format(chosen.replace("#", raw), values)',
			'    }',
			''
		);
	}
	lines.push('    companion object {');
	if (table.format) {
		lines.push(
			'        /** CLDR integer plural categories for the languages whose copy uses plural tokens. */',
			'        fun pluralCategory(n: Int, language: String): String {',
			'            val ten = n % 10',
			'            val hundred = n % 100',
			'            return when (language) {',
			'                "cs", "sk" -> if (n == 1) "one" else if (n in 2..4) "few" else "other"',
			'                "pl" -> if (n == 1) "one" else if (ten in 2..4 && hundred !in 12..14) "few" else "many"',
			'                "ru", "uk", "hr", "sr", "bs" -> when {',
			'                    ten == 1 && hundred != 11 -> "one"',
			'                    ten in 2..4 && hundred !in 12..14 -> "few"',
			'                    language == "ru" || language == "uk" -> "many"',
			'                    else -> "other"',
			'                }',
			'                else -> if (n == 1) "one" else "other"',
			'            }',
			'        }',
			''
		);
	}
	lines.push(
		'        /** Every language code with generated copy, sorted. */',
		`        val supportedLanguages: List<String> = listOf(${languages
			.map(({ language }) => kotlinString(language))
			.join(', ')})`,
		'',
		'        /**',
		'         * Returns the copy for a language code such as `de` or `pt-BR`.',
		'         * Matching ignores case and tries the full code, then the part',
		`         * before \`-\`, then falls back to \`${FALLBACK_LANGUAGE}\`.`,
		'         */',
		`        fun forLanguage(code: String): ${type} {`,
		"            val normalized = code.lowercase(Locale.ROOT).replace('_', '-')",
		'            return copyFor(normalized)',
		"                ?: copyFor(normalized.substringBefore('-'))",
		'                ?: FALLBACK',
		'        }',
		'',
		`        private fun copyFor(code: String): ${type}? =`,
		`            if (code == ${kotlinString(FALLBACK_LANGUAGE)}) FALLBACK else others[code]`,
		'',
		'        /** Inline, so this language never depends on the resource. */',
		`        private val FALLBACK = ${type}(`,
		`            language = ${kotlinString(FALLBACK_LANGUAGE)},`
	);
	for (const name of names) {
		lines.push(
			`            ${name} = ${kotlinString(fallback.values[name] ?? '')},`
		);
	}
	lines.push(
		'        )',
		'',
		'        /**',
		`         * Every other language, read once from \`${resourceName}\` beside this class.`,
		'         * Keeping translation text out of class files keeps it out of method and',
		'         * constant-pool limits. A missing or malformed entry falls back to English.',
		'         */',
		`        private val others: Map<String, ${type}> by lazy {`,
		`            val text = ${type}::class.java.getResourceAsStream(${kotlinString(resourceName)})`,
		'                ?.use { it.readBytes().toString(Charsets.UTF_8) } ?: return@lazy emptyMap()',
		'            val root = runCatching { Json.parseToJsonElement(text) as? JsonObject }.getOrNull()',
		'                ?: return@lazy emptyMap()',
		'            root.mapNotNull { (language, element) -> parse(language, element as? JsonObject) }.toMap()',
		'        }',
		'',
		`        private fun parse(language: String, values: JsonObject?): Pair<String, ${type}>? {`,
		'            if (values == null) return null',
		'            fun text(name: String): String? =',
		'                (values[name] as? JsonPrimitive)?.takeIf { it.isString }?.content',
		`            return language to ${type}(`,
		'                language = language,'
	);
	for (const name of names) {
		lines.push(
			`                ${name} = text(${kotlinString(name)}) ?: return null,`
		);
	}
	lines.push('            )', '        }', '    }', '}', '');
	return lines.join('\n');
};

/**
 * Renders the Android JSON resource: every language except English, keyed by
 * language code and property name.
 *
 * @param languages - Output of {@link collectNativeIabCopy}.
 */
export const renderKotlinResource = function renderKotlinResource(
	languages: NativeIabCopyLanguage[],
	table: NativeCopyTable = IAB_TABLE
): string {
	const names = table.keys.map(([name]) => name);
	const others = Object.fromEntries(
		languages
			.filter(({ language }) => language !== FALLBACK_LANGUAGE)
			.map(({ language, values }) => [
				language,
				Object.fromEntries(names.map((name) => [name, values[name] ?? ''])),
			])
	);
	return `${JSON.stringify(others, null, '\t')}\n`;
};

/** One generated file and its expected contents. */
export interface NativeIabCopyOutput {
	path: string;
	contents: string;
}

/**
 * Builds every generated file from the current translations.
 *
 * @returns The Swift, Kotlin and Android resource outputs of both tables.
 */
export const buildNativeIabCopy =
	function buildNativeIabCopy(): NativeIabCopyOutput[] {
		const translations = translationsWithNativeLabels();
		return [IAB_TABLE, CONSENT_TABLE].flatMap((table) => {
			const languages = collectNativeIabCopy(translations, table);
			return [
				{ contents: renderSwift(languages, table), path: table.swiftOutput },
				{
					contents: renderKotlin(languages, table),
					path: table.kotlinOutput,
				},
				{
					contents: renderKotlinResource(languages, table),
					path: table.kotlinResourceOutput,
				},
			];
		});
	};

const readIfPresent = (path: string) => {
	try {
		return readFileSync(path, 'utf8');
	} catch {
		return undefined;
	}
};

/**
 * Lists generated files whose contents on disk differ from the translations.
 *
 * @returns Repo-relative paths that are stale or missing.
 */
export const checkNativeIabCopy = function checkNativeIabCopy(): string[] {
	return buildNativeIabCopy()
		.filter(({ contents, path }) => readIfPresent(path) !== contents)
		.map(({ path }) => path.slice(REPO_ROOT.length));
};

const main = function main() {
	if (process.argv.includes('--check')) {
		const stale = checkNativeIabCopy();
		if (stale.length > 0) {
			console.error(
				`Native consent copy is out of date. Run bun run generate:native-iab-copy.\n${stale.join('\n')}`
			);
			process.exit(1);
		}
		console.log('Native consent copy is up to date.');
		return;
	}
	for (const { contents, path } of buildNativeIabCopy()) {
		mkdirSync(dirname(path), { recursive: true });
		writeFileSync(path, contents);
		console.log(
			`Wrote ${path.slice(REPO_ROOT.length)} (${Buffer.byteLength(contents)} bytes)`
		);
	}
};

if (import.meta.main) {
	main();
}
