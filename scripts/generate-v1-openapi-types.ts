#!/usr/bin/env bun

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import type { OpenAPI3 } from 'openapi-typescript';
import { format } from 'oxfmt';

import repoConfig from '../oxfmt.sdk.config';

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const DIRECTORY = join(REPO_ROOT, 'packages/sdk/schema/vendor/backend-openapi');

const DOCUMENT_PATH = join(DIRECTORY, 'openapi.json');
/**
 * Every copy of the types. `@inth/node` publishes on its own, so it keeps a
 * copy inside its source rather than importing the private schema package.
 */
const TYPES_PATHS = [
	join(DIRECTORY, 'openapi.generated.ts'),
	join(REPO_ROOT, 'packages/sdk/node/src/generated/openapi.ts'),
];

const HEADER = `// Generated by scripts/generate-v1-openapi-types.ts from
// packages/sdk/schema/vendor/backend-openapi/openapi.json. Do not edit.
// Regenerate with \`pnpm --dir scripts generate:v1-openapi-types\`.
`;

const { ignorePatterns: _ignorePatterns, ...formatOptions } = repoConfig;

/** The types file the document generates, formatted as the repo formats. */
const renderTypes = async function renderTypes(): Promise<string> {
	const document = JSON.parse(readFileSync(DOCUMENT_PATH, 'utf8')) as OpenAPI3;
	const ast = await openapiTS(document, {
		defaultNonNullable: false,
		emptyObjectsUnknown: true,
	});
	const result = await format(
		'openapi.generated.ts',
		`${HEADER}\n${astToString(ast)}`,
		formatOptions
	);
	if (result.errors.length > 0) {
		throw new Error(
			`Formatting the generated types failed: ${JSON.stringify(result.errors)}`
		);
	}
	return result.code;
};

/** Whether every committed copy matches what the document generates. */
export const checkV1OpenApiTypes =
	async function checkV1OpenApiTypes(): Promise<boolean> {
		const types = await renderTypes();
		return TYPES_PATHS.every((path) => readFileSync(path, 'utf8') === types);
	};

if (import.meta.main) {
	const types = await renderTypes();
	for (const path of TYPES_PATHS) {
		writeFileSync(path, types);
	}
}
