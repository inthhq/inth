#!/usr/bin/env bun

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import type { OpenAPI3 } from 'openapi-typescript';
import { format } from 'oxfmt';

import repoConfig from '../oxfmt.sdk.config';

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const DIRECTORY = join(REPO_ROOT, 'packages/sdk/schema/vendor/backend-openapi');

const DOCUMENT_PATH = join(DIRECTORY, 'openapi.json');
const TYPES_PATH = join(DIRECTORY, 'openapi.generated.ts');

const HEADER = `// Generated by scripts/generate-v1-openapi-types.ts from openapi.json. Do not edit.
// Regenerate with \`pnpm --dir scripts generate:v1-openapi-types\`.
`;

/**
 * Schemas in the document that hold `$defs` of their own and point at them
 * as `#/$defs/<name>`. A `$ref` resolves against the document, which has no
 * `$defs`, so no tool can resolve these. Each is moved to
 * `components.schemas` under the name given, and its references follow.
 *
 * The init answer's category condition (a category, or `and`, `or` and
 * `not` over conditions) is the only one. The backend should emit it as a
 * component; when it does, remove the entry here.
 */
const NESTED_DEFS: Record<string, Record<string, string>> = {
	'/paths/~1v1~1consent~1init/get/responses/200/content/application~1json/schema':
		{ '0': 'V1CategoryCondition' },
};

type Json = Record<string, unknown>;

const isObject = (value: unknown): value is Json =>
	typeof value === 'object' && value !== null && !Array.isArray(value);

const pointerOf = (path: string[]): string =>
	path.length === 0
		? ''
		: `/${path.map((key) => key.replaceAll('~', '~0').replaceAll('/', '~1')).join('/')}`;

/**
 * The document with every schema listed in {@link NESTED_DEFS} moved to
 * `components.schemas`. Throws when the document holds `$defs` this does not
 * list, or no longer holds one it lists, so the list cannot go stale.
 */
export const hoistNestedDefs = function hoistNestedDefs(document: Json): Json {
	const copy = structuredClone(document);
	const components = isObject(copy.components) ? copy.components : {};
	const schemas = isObject(components.schemas) ? components.schemas : {};
	const found = new Set<string>();

	const rewrite = (node: unknown, names: Record<string, string>): void => {
		if (Array.isArray(node)) {
			for (const item of node) {
				rewrite(item, names);
			}
			return;
		}
		if (!isObject(node)) {
			return;
		}
		const ref = node.$ref;
		if (typeof ref === 'string' && ref.startsWith('#/$defs/')) {
			const name = names[ref.slice('#/$defs/'.length)];
			if (name === undefined) {
				throw new Error(`Unlisted reference ${ref}`);
			}
			node.$ref = `#/components/schemas/${name}`;
		}
		for (const value of Object.values(node)) {
			rewrite(value, names);
		}
	};

	const visit = (node: unknown, path: string[]): void => {
		if (Array.isArray(node)) {
			node.forEach((item, index) => {
				visit(item, [...path, String(index)]);
			});
			return;
		}
		if (!isObject(node)) {
			return;
		}
		if (isObject(node.$defs)) {
			const pointer = pointerOf(path);
			const names = NESTED_DEFS[pointer];
			const keys = Object.keys(node.$defs);
			if (
				names === undefined ||
				keys.length !== Object.keys(names).length ||
				keys.some((key) => names[key] === undefined)
			) {
				throw new Error(`Unlisted $defs at ${pointer}: ${keys.join(', ')}`);
			}
			found.add(pointer);
			const defs = node.$defs;
			delete node.$defs;
			rewrite(node, names);
			for (const [key, schema] of Object.entries(defs)) {
				rewrite(schema, names);
				schemas[names[key] as string] = schema;
			}
			return;
		}
		for (const [key, value] of Object.entries(node)) {
			visit(value, [...path, key]);
		}
	};

	visit(copy, []);
	const missing = Object.keys(NESTED_DEFS).filter((key) => !found.has(key));
	if (missing.length > 0) {
		throw new Error(`No $defs left at ${missing.join(', ')}; remove the entry`);
	}
	copy.components = { ...components, schemas };
	return copy;
};

const { ignorePatterns: _ignorePatterns, ...formatOptions } = repoConfig;

/** The types file the document generates, formatted as the repo formats. */
const renderTypes = async function renderTypes(
	document: Json
): Promise<string> {
	const ast = await openapiTS(
		hoistNestedDefs(document) as unknown as OpenAPI3,
		{
			defaultNonNullable: false,
			emptyObjectsUnknown: true,
		}
	);
	const result = await format(
		'openapi.generated.ts',
		`${HEADER}\n${astToString(ast)}`,
		formatOptions
	);
	if (result.errors.length > 0) {
		throw new Error(
			`Formatting the generated types failed: ${JSON.stringify(result.errors)}`
		);
	}
	return result.code;
};

const readDocument = (): Json =>
	JSON.parse(readFileSync(DOCUMENT_PATH, 'utf8')) as Json;

/** Whether the committed types match what the document generates. */
export const checkV1OpenApiTypes =
	async function checkV1OpenApiTypes(): Promise<boolean> {
		return (
			readFileSync(TYPES_PATH, 'utf8') ===
			(await renderTypes(readDocument()))
		);
	};

if (import.meta.main) {
	writeFileSync(TYPES_PATH, await renderTypes(readDocument()));
}
