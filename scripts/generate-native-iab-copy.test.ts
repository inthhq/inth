import { describe, expect, it } from 'vite-plus/test';

import {
	checkNativeIabCopy,
	collectNativeIabCopy,
	IAB_COPY_KEYS,
	kotlinString,
	propertyName,
	renderKotlin,
	renderKotlinResource,
	renderSwift,
	swiftString,
} from './generate-native-iab-copy';

describe('generate-native-iab-copy', () => {
	it('matches the committed Swift and Kotlin files', () => {
		// Fails after a translation change until `bun run generate:native-iab-copy`.
		expect(checkNativeIabCopy()).toEqual([]);
	});

	it('names properties after the key path', () => {
		expect(propertyName('banner.title')).toBe('bannerTitle');
		expect(propertyName('app.description')).toBe('appDescription');
		expect(propertyName('common.acceptAll')).toBe('commonAcceptAll');
		expect(propertyName('preferenceCenter.vendorList.privacyPolicy')).toBe(
			'preferenceCenterVendorListPrivacyPolicy'
		);
	});

	// Built from code points so the test source holds no invisible characters.
	const rightToLeftMark = String.fromCodePoint(0x20_0f);
	const astralTag = String.fromCodePoint(0xe_00_01);
	const kotlinTemplate = ['$', '{e}'].join('');

	it('escapes Swift literals', () => {
		expect(swiftString('a"b\\c$d\n{x}')).toBe(String.raw`"a\"b\\c$d\n{x}"`);
		expect(swiftString(`${rightToLeftMark}abc`)).toBe('"\\u{200F}abc"');
	});

	it('escapes Kotlin literals, including template dollars', () => {
		expect(kotlinString(`a"b\\c$d${kotlinTemplate}\n`)).toBe(
			`"a\\"b\\\\c\\$d\\${kotlinTemplate}\\n"`
		);
		expect(kotlinString(`${rightToLeftMark}abc`)).toBe('"\\u200Fabc"');
		expect(kotlinString(astralTag)).toBe('"\\uDB40\\uDC01"');
	});

	it('fails on a missing key instead of inventing copy', () => {
		expect(() =>
			collectNativeIabCopy({ en: { iab: { banner: { title: 'Privacy' } } } })
		).toThrow(/en: iab\.app\.description/u);
	});

	it('renders every key for every language in a stable order', () => {
		const languages = collectNativeIabCopy();
		const swift = renderSwift(languages);
		const kotlin = renderKotlin(languages);

		expect(swift).toBe(renderSwift(collectNativeIabCopy()));
		expect(
			swift.startsWith(
				'// Generated by scripts/generate-native-iab-copy.ts. Do not edit.'
			)
		).toBe(true);
		expect(
			kotlin.startsWith(
				'// Generated by scripts/generate-native-iab-copy.ts. Do not edit.'
			)
		).toBe(true);
		expect(languages.map(({ language }) => language)).toContain('en');
		for (const keyPath of IAB_COPY_KEYS) {
			const name = propertyName(keyPath);
			expect(swift).toContain(`public let ${name}: String`);
			expect(kotlin).toContain(`val ${name}: String,`);
		}
	});

	it('keeps Android translation text in the resource, not the class', () => {
		const languages = collectNativeIabCopy();
		const kotlin = renderKotlin(languages);
		const resource = JSON.parse(renderKotlinResource(languages)) as Record<
			string,
			Record<string, string>
		>;
		const others = languages.filter(({ language }) => language !== 'en');

		expect(Object.keys(resource)).toEqual(
			others.map(({ language }) => language)
		);
		for (const { language, values } of others) {
			expect(resource[language]).toEqual(values);
			// The class carries English only.
			expect(kotlin).not.toContain(kotlinString(values.appDescription ?? ''));
		}
	});
});
