#!/usr/bin/env bun

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import type { OpenAPI3 } from 'openapi-typescript';
import { format } from 'vite-plus/fmt';

import { fmtConfig as repoConfig } from '../oxfmt.sdk.config';
import { openApiToValibot } from './openapi-to-valibot';
import type { OpenApiDocument } from './openapi-to-valibot';

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));

const DOCUMENT_PATH = join(
	REPO_ROOT,
	'packages/sdk/schema/vendor/backend-openapi/openapi.json'
);

/** Where the schema package keeps what the document generates. */
const GENERATED = join(REPO_ROOT, 'packages/sdk/schema/src/api/v1/generated');

/**
 * Every copy of the types. `@inth/node` publishes on its own, so it keeps a
 * copy inside its source rather than importing the private schema package.
 */
const TYPES_PATHS = [
	join(GENERATED, 'types.ts'),
	join(REPO_ROOT, 'packages/sdk/node/src/generated/openapi.ts'),
];

const SCHEMAS_PATH = join(GENERATED, 'schemas.ts');

const header = (
	what: string
) => `// ${what} generated by scripts/generate-v1-openapi.ts from
// packages/sdk/schema/vendor/backend-openapi/openapi.json. Do not edit.
// Regenerate with \`pnpm --dir scripts generate:v1-openapi\`.
`;

const { ignorePatterns: _ignorePatterns, ...formatOptions } = repoConfig;

/** `source`, formatted as the repo formats. */
const formatted = async function formatted(
	name: string,
	source: string
): Promise<string> {
	const result = await format(name, source, formatOptions);
	if (result.errors.length > 0) {
		throw new Error(
			`Formatting ${name} failed: ${JSON.stringify(result.errors)}`
		);
	}
	return result.code;
};

const readDocument = (): unknown =>
	JSON.parse(readFileSync(DOCUMENT_PATH, 'utf8'));

/** The types file the document generates. */
const renderTypes = async function renderTypes(): Promise<string> {
	const ast = await openapiTS(readDocument() as OpenAPI3, {
		defaultNonNullable: false,
		emptyObjectsUnknown: true,
	});
	return formatted('types.ts', `${header('Types')}\n${astToString(ast)}`);
};

/** The Valibot schemas file the document generates. */
const renderSchemas = function renderSchemas(): Promise<string> {
	return formatted(
		'schemas.ts',
		openApiToValibot(readDocument() as OpenApiDocument, {
			header: header('Valibot schemas'),
			runtimeModule: '../json-schema',
			typesModule: './types',
		})
	);
};

/** Each generated file and what the document generates for it. */
const render = async function render(): Promise<[string, string][]> {
	const [types, schemas] = await Promise.all([renderTypes(), renderSchemas()]);
	return [
		...TYPES_PATHS.map((path): [string, string] => [path, types]),
		[SCHEMAS_PATH, schemas],
	];
};

/** The committed files that differ from what the document generates. */
export const staleV1OpenApiFiles =
	async function staleV1OpenApiFiles(): Promise<string[]> {
		const files = await render();
		return files
			.filter(([path, content]) => {
				try {
					return readFileSync(path, 'utf8') !== content;
				} catch {
					return true;
				}
			})
			.map(([path]) => path.slice(REPO_ROOT.length));
	};

if (import.meta.main) {
	for (const [path, content] of await render()) {
		writeFileSync(path, content);
	}
}
