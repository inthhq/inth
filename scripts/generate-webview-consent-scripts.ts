#!/usr/bin/env bun

/**
 * Copies the WebView consent scripts from `packages/native-protocol/webview/` into the
 * Swift core, the Kotlin core and the React Native package, so all three
 * inject the same bytes.
 *
 * Each source file is one parenthesized function expression. A platform calls
 * it as `<script>(<origins>, <token>, <state>);` with JSON arguments. See
 * "WebView consent" in `packages/native-protocol/CONTRACT.md`.
 *
 * Run without flags after editing a script. `--check` compares instead of
 * writing and exits non-zero on drift; `generate-webview-consent-scripts.test.ts`
 * runs the same check in `bun run test:scripts`.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const SOURCE_DIR = join(REPO_ROOT, 'packages/native-protocol/webview');

export const SWIFT_OUTPUT = join(
	REPO_ROOT,
	'packages/swift/Sources/C15tCore/generated/webview-consent-scripts.generated.swift'
);
export const KOTLIN_OUTPUT = join(
	REPO_ROOT,
	'packages/android/c15t-core/src/main/kotlin/com/c15t/core/webview/generated/webview-consent-scripts.kt'
);
export const TYPESCRIPT_OUTPUT = join(
	REPO_ROOT,
	'packages/react-native/src/webview/scripts.generated.ts'
);

const HEADER =
	'Generated by scripts/generate-webview-consent-scripts.ts from packages/native-protocol/webview. Do not edit.';

/** The two scripts, read from their canonical files. */
export interface WebViewConsentScripts {
	documentStart: string;
	update: string;
}

export const readScripts = function readScripts(
	directory: string = SOURCE_DIR
): WebViewConsentScripts {
	const read = (name: string) => {
		// The formatter ends the expression statement with a semicolon; the
		// call appends the arguments, so drop it.
		const source = readFileSync(join(directory, name), 'utf8')
			.trim()
			.replace(/;$/u, '');
		if (!source.startsWith('(function (') || !source.endsWith('})')) {
			throw new Error(`${name} must be one parenthesized function expression`);
		}
		// Kotlin raw strings expand `$` and end at `"""`; Swift raw strings end
		// at `"""#`. Keeping both out lets every platform embed the bytes as is.
		if (source.includes('$') || source.includes('"""')) {
			throw new Error(`${name} must not contain "$" or '"""'`);
		}
		return source;
	};
	return {
		documentStart: read('document-start.js'),
		update: read('update.js'),
	};
};

export const renderSwift = function renderSwift(
	scripts: WebViewConsentScripts
): string {
	return `// ${HEADER}

/// The WebView consent scripts, byte for byte the files in
/// \`packages/native-protocol/webview\`. Each is one parenthesized function expression a helper
/// calls with JSON arguments: \`<script>(<origins>, <token>, <state>);\`.
enum WebViewConsentScripts {
    static let documentStart = #"""
${scripts.documentStart}
"""#

    static let update = #"""
${scripts.update}
"""#
}
`;
};

export const renderKotlin = function renderKotlin(
	scripts: WebViewConsentScripts
): string {
	return `// ${HEADER}
package com.c15t.core.webview

/**
 * The WebView consent scripts, byte for byte the files in
 * \`packages/native-protocol/webview\`. Each is one parenthesized function expression a helper
 * calls with JSON arguments: \`<script>(<origins>, <token>, <state>);\`.
 */
internal object WebViewConsentScripts {
	const val DOCUMENT_START: String = """${scripts.documentStart}"""

	const val UPDATE: String = """${scripts.update}"""
}
`;
};

export const renderTypeScript = function renderTypeScript(
	scripts: WebViewConsentScripts
): string {
	return `// ${HEADER}

/**
 * Runs at document start in a WebView. Call it as
 * \`<script>(<origins>, <token>, <state>);\` with JSON arguments.
 */
export const DOCUMENT_START_SCRIPT = ${JSON.stringify(scripts.documentStart)};

/** Pushes a new state into a page the document-start script prepared. */
export const UPDATE_SCRIPT = ${JSON.stringify(scripts.update)};
`;
};

const OUTPUTS = [
	[SWIFT_OUTPUT, renderSwift],
	[KOTLIN_OUTPUT, renderKotlin],
	[TYPESCRIPT_OUTPUT, renderTypeScript],
] as const;

/** Paths whose committed content differs from what the sources produce. */
export const checkWebViewConsentScripts =
	function checkWebViewConsentScripts(): string[] {
		const scripts = readScripts();
		return OUTPUTS.filter(([path, render]) => {
			try {
				return readFileSync(path, 'utf8') !== render(scripts);
			} catch {
				return true;
			}
		}).map(([path]) => path);
	};

const main = function main(): void {
	if (process.argv.includes('--check')) {
		const stale = checkWebViewConsentScripts();
		if (stale.length > 0) {
			console.error(
				`Out of date, run \`bun run generate:webview-consent-scripts\`:\n${stale.join('\n')}`
			);
			process.exit(1);
		}
		return;
	}
	const scripts = readScripts();
	for (const [path, render] of OUTPUTS) {
		mkdirSync(dirname(path), { recursive: true });
		writeFileSync(path, render(scripts));
	}
};

if (import.meta.main) {
	main();
}
