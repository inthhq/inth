/**
 * Generates `src/generated/styles.ts` from the built `@inth/sdk-ui` artifacts.
 *
 * The script-tag build has to carry the stylesheet as a string so it can
 * drop it into a shadow root, and it needs the hashed class names without
 * importing the CSS-module JS (whose `import './x.css'` side effect would
 * make the bundler emit a separate stylesheet). Reading both from the
 * built `dist/` of `@inth/sdk-ui` keeps this package's DOM in lockstep
 * with the React, Svelte and Vue surfaces: same classes, same tokens.
 * Rules only other frameworks' surfaces can match are dropped, and so are
 * comments and formatting whitespace (`prune-stylesheet.ts`).
 *
 * Runs from `prebuild`; the output is gitignored.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
	collectClassNames,
	compactStylesheet,
	pruneStylesheet,
} from './prune-stylesheet';

const uiDist = dirname(
	fileURLToPath(import.meta.resolve('@inth/sdk-ui/styles.css'))
);
const outputDir = resolve(import.meta.dirname, '../src/generated');

/**
 * Class maps the stock sheet's surfaces render against: the shared parts,
 * the trigger, the opt-in confirmation and the IAB surfaces' switches.
 */
const COMPONENTS = {
	actions: 'consent-actions',
	branding: 'branding',
	button: 'button',
	legalLinks: 'legal-links',
	optOutConfirmation: 'opt-out-confirmation',
	switch: 'switch',
	trigger: 'consent-dialog-trigger',
} as const;

/**
 * The prompt's and the dialog's class maps, by generated file name. Their
 * rules are not in the stock sheet: each surface adds `@inth/sdk-ui`'s
 * sheets for it when it renders.
 */
const SURFACE_COMPONENTS = {
	banner: 'consent-banner',
	card: 'consent-card',
	dialog: 'consent-dialog',
	drawer: 'consent-drawer',
	expand: 'consent-expand',
	surface: 'consent-surface',
} as const;

const readClassMap = async function readClassMap(
	component: string
): Promise<Record<string, string>> {
	// The `.node.js` variant is the class map without the CSS import.
	const source = await readFile(
		fileURLToPath(
			import.meta.resolve(`@inth/sdk-ui/styles/components/${component}`)
		),
		'utf8'
	);
	const match = /export default(?<map>\{.*\});?\s*$/su.exec(source);
	if (!match?.groups?.map) {
		throw new Error(
			`@inth/sdk-browser: could not parse class map for ${component}`
		);
	}
	// The map is a plain object literal with unquoted keys; JSON needs quotes.
	const json = match.groups.map
		.replace(
			/(?<before>[{,])\s*(?<key>[A-Za-z0-9_$-]+)\s*:/gu,
			'$<before>"$<key>":'
		)
		.replace(/'/gu, '"');
	return JSON.parse(json) as Record<string, string>;
};

const main = async function main(): Promise<void> {
	const entries = await Promise.all(
		Object.entries(COMPONENTS).map(async ([key, component]) => [
			key,
			await readClassMap(component),
		])
	);
	const classes = Object.fromEntries(entries) as Record<
		keyof typeof COMPONENTS,
		Record<string, string>
	>;
	const iabClasses = {
		banner: await readClassMap('iab-consent-banner'),
		dialog: await readClassMap('iab-consent-dialog'),
	};
	// Both entries render into one shadow root, so a rule either surface can
	// match stays in both sheets.
	const rendered = collectClassNames([classes, iabClasses]);
	// The sheet already pairs every `:root` with `:host`, so it applies
	// inside the shadow root as published. It holds the dialog rules too.
	const stylesheet = compactStylesheet(
		pruneStylesheet(
			await readFile(join(uiDist, 'styles.css'), 'utf8'),
			rendered
		)
	);

	const banner = [
		'// Generated by scripts/build-styles.ts from the built @inth/sdk-ui package.',
		'// Do not edit; rerun `bun prebuild`.',
		'',
	].join('\n');
	const body = [
		`export const stylesheet: string = ${JSON.stringify(stylesheet)};`,
		'',
		`export const classes = ${JSON.stringify(classes, null, '\t')} as const;`,
		'',
	].join('\n');

	await mkdir(outputDir, { recursive: true });
	await writeFile(join(outputDir, 'styles.ts'), `${banner}\n${body}`);
	const iabStylesheet = compactStylesheet(
		pruneStylesheet(
			await readFile(join(uiDist, 'iab/styles.css'), 'utf8'),
			rendered
		)
	);
	await writeFile(
		join(outputDir, 'iab-styles.ts'),
		`${banner}\nexport const stylesheet: string = ${JSON.stringify(iabStylesheet)};\nexport const classes = ${JSON.stringify(iabClasses, null, '\t')} as const;\n`
	);
	// One module per class map, so a page bundles only the container it
	// shows.
	const surfacesDir = join(outputDir, 'ui');
	await mkdir(surfacesDir, { recursive: true });
	await Promise.all(
		Object.entries(SURFACE_COMPONENTS).map(async ([file, component]) =>
			writeFile(
				join(surfacesDir, `${file}.ts`),
				`${banner}\nexport const classes = ${JSON.stringify(await readClassMap(component), null, '\t')} as const;\n`
			)
		)
	);
};

await main();
