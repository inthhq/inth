/**
 * Writes the window globals a vendor manifest may never declare.
 *
 * Opens Chromium on a secure page, reads every property name on `window`
 * and its prototype chain, and adds the ECMAScript globals of a bare V8
 * context. It writes two files in `@inth/sdk-core`:
 *
 * - `manifest-runtime/platform-globals.ts`: the names the parser refuses as
 *   roots, less two groups other checks cover: event handler properties
 *   (`on` and a lowercase word) and interface objects (`HTMLDivElement`),
 *   which a browser refuses by reading `window` itself. A few interface
 *   objects that send requests, run code or reach a document stay listed,
 *   so a server parse refuses them too.
 * - `manifest-runtime/__tests__/fixtures/chromium-globals.json`: every name,
 *   for the tests that check the list and each vendor's roots.
 *
 * Run from `packages/sdk/browser`: `pnpm exec vpx scripts/platform-globals.ts`,
 * then `pnpm run fmt` in `packages/sdk/core`.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createContext, runInContext } from 'node:vm';

import { chromium } from 'playwright';

/** Interface objects listed by name, so a parse outside a browser refuses them. */
const LISTED_INTERFACES = [
	'Audio',
	'Blob',
	'BroadcastChannel',
	'CustomEvent',
	'Document',
	'DOMParser',
	'Element',
	'Event',
	'EventSource',
	'EventTarget',
	'FileReader',
	'FormData',
	'Headers',
	'History',
	'HTMLElement',
	'HTMLIFrameElement',
	'HTMLScriptElement',
	'Image',
	'Location',
	'MessageChannel',
	'MutationObserver',
	'Navigation',
	'Navigator',
	'Node',
	'Notification',
	'Option',
	'Range',
	'Request',
	'Response',
	'ServiceWorker',
	'SharedWorker',
	'Storage',
	'URL',
	'WebSocket',
	'Window',
	'Worker',
	'XMLHttpRequest',
	'XMLSerializer',
	'XSLTProcessor',
];

const here = dirname(fileURLToPath(import.meta.url));
const runtimeDir = resolve(here, '../../core/src/manifest-runtime');

const browser = await chromium.launch();
const page = await browser.newPage();
// A secure context, so names such as `caches` and `cookieStore` exist.
await page.route('https://inth.test/', (route) =>
	route.fulfill({ body: '<!doctype html>', contentType: 'text/html' })
);
await page.goto('https://inth.test/');
const fromWindow = await page.evaluate(() => {
	// No prototype, so `constructor` and `__proto__` are keys like any other.
	const names: Record<string, boolean> = Object.create(null);
	const source = Function.prototype.toString;
	for (
		let object: object | null = window;
		object;
		object = Object.getPrototypeOf(object)
	) {
		for (const name of Object.getOwnPropertyNames(object)) {
			const descriptor = Object.getOwnPropertyDescriptor(object, name);
			const value =
				descriptor && 'value' in descriptor ? descriptor.value : undefined;
			names[name] =
				names[name] === true ||
				(/^[A-Z]/u.test(name) &&
					typeof value === 'function' &&
					!descriptor?.enumerable &&
					source.call(value).includes('[native code]') &&
					'prototype' in value);
		}
	}
	return names;
});
await browser.close();

const builtIns = runInContext(
	'Object.getOwnPropertyNames(globalThis)',
	createContext()
) as string[];

const isHandler = (name: string) => /^on[a-z]+$/u.test(name);
const all = new Set([...Object.keys(fromWindow), ...builtIns]);
const refused = [...all]
	.filter(
		(name) =>
			!isHandler(name) &&
			(!fromWindow[name] ||
				builtIns.includes(name) ||
				LISTED_INTERFACES.includes(name))
	)
	.sort();
for (const name of LISTED_INTERFACES) {
	if (!all.has(name)) {
		throw new Error(`${name} is not a window global in this browser`);
	}
}

writeFileSync(
	resolve(runtimeDir, '__tests__/fixtures/chromium-globals.json'),
	`${JSON.stringify(
		Object.fromEntries(
			[...all].sort().map((name) => [name, fromWindow[name] ?? false])
		),
		null,
		'\t'
	)}\n`
);
writeFileSync(
	resolve(runtimeDir, 'platform-globals.ts'),
	`/**
 * Window and ECMAScript globals a manifest may never declare as a root.
 * Generated by \`packages/sdk/browser/scripts/platform-globals.ts\` from
 * Chromium's window; edit the script, not this file. Event handler names
 * and most interface objects are left out: \`globals.ts\` refuses them by
 * pattern and by reading \`window\`.
 *
 * @internal
 */
export const PLATFORM_GLOBALS =
	${JSON.stringify(refused.join(' '))};
`
);
console.log(`${all.size} names, ${refused.length} listed`);
