import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import {
  mkdir,
  mkdtemp,
  readdir,
  readFile,
  realpath,
  rm,
  writeFile,
} from "node:fs/promises";
import os from "node:os";
import path from "node:path";

import { z } from "zod";

const resultSchema = z.object({
  data: z.object({
    applied: z.boolean(),
    files: z.array(z.object({ action: z.string(), path: z.string() })),
    options: z.object({
      backendUrl: z.string(),
      categories: z.array(z.string()),
    }),
    platform: z.string(),
    platforms: z.array(z.string()),
    root: z.string(),
    skipped: z.array(z.string()),
    steps: z.array(z.string()),
  }),
  ok: z.literal(true),
});

const errorSchema = z.object({
  error: z.object({ code: z.string(), message: z.string() }),
  ok: z.literal(false),
});

const appJsonSchema = z.object({
  expo: z.object({
    ios: z.object({ bundleIdentifier: z.string() }),
    name: z.string(),
    plugins: z.array(
      z.union([
        z.string(),
        z.tuple([
          z.string(),
          z.object({
            consentCategories: z.array(z.string()),
            projectUrl: z.string(),
          }),
        ]),
      ])
    ),
  }),
});

const PRIVACY = "https://demo.example/privacy";

// `inth mobile setup` only writes files in the app, so it must run with no
// session, no keychain and nowhere to keep state.
const accountlessEnv = async (parent: string): Promise<NodeJS.ProcessEnv> => {
  const home = path.join(parent, "mobile-home");
  await mkdir(home);
  const blocked = path.join(home, "unavailable");
  await writeFile(blocked, "A file, so no state directory fits inside it.");
  const env: NodeJS.ProcessEnv = {
    ...process.env,
    APPDATA: blocked,
    DBUS_SESSION_BUS_ADDRESS: `unix:path=${path.join(home, "missing-bus")}`,
    HOME: home,
    INTH_TELEMETRY_DISABLED: "1",
    USERPROFILE: home,
    XDG_CONFIG_HOME: blocked,
    XDG_STATE_HOME: blocked,
  };
  delete env.INTH_TOKEN;
  delete env.INTH_DEV_API_ORIGIN;
  delete env.INTH_DEV_DASHBOARD_ORIGIN;
  return env;
};

export const verifyMobile = async (binary: string): Promise<void> => {
  const parent = await realpath(
    await mkdtemp(path.join(os.tmpdir(), "inth-mobile-"))
  );
  try {
    const env = await accountlessEnv(parent);
    const expo = path.join(parent, "expo");
    await mkdir(path.join(expo, "app", "screens"), { recursive: true });
    await writeFile(
      path.join(expo, "package.json"),
      JSON.stringify({ dependencies: { expo: "54.0.0" }, name: "demo" })
    );
    await writeFile(path.join(expo, "tsconfig.json"), "{}");
    await writeFile(path.join(expo, "app", "_layout.tsx"), "");
    const appJson =
      '{\n  "expo": {\n    "name": "demo",\n    "plugins": ["expo-router"],\n    "ios": { "bundleIdentifier": "app.demo" }\n  }\n}\n';
    await writeFile(path.join(expo, "app.json"), appJson);
    const setup = (args: string[], cwd = path.join(expo, "app", "screens")) =>
      spawnSync(binary, ["mobile", "setup", ...args, "--json"], {
        cwd,
        encoding: "utf-8",
        env,
        timeout: 30_000,
      });

    const dry = setup([
      "--backend-url",
      "Demo.inth.app/",
      "--privacy-policy-url",
      PRIVACY,
      "--dry-run",
    ]);
    assert.equal(dry.status, 0, dry.stdout + dry.stderr);
    const planned = resultSchema.parse(JSON.parse(dry.stdout)).data;
    assert.equal(planned.platform, "expo");
    assert.equal(planned.root, expo);
    assert.equal(planned.applied, false);
    assert.deepEqual(
      planned.files.map((file) => `${file.action} ${file.path}`),
      ["update app.json", "create inth/privacy-app.tsx"]
    );
    assert.equal(await readFile(path.join(expo, "app.json"), "utf-8"), appJson);

    const written = setup([
      "--backend-url",
      "Demo.inth.app/",
      "--privacy-policy-url",
      PRIVACY,
      "--categories",
      "marketing",
    ]);
    assert.equal(written.status, 0, written.stdout + written.stderr);
    const config = appJsonSchema.parse(
      JSON.parse(await readFile(path.join(expo, "app.json"), "utf-8"))
    );
    assert.deepEqual(config.expo.plugins, [
      "expo-router",
      [
        "@inth/react-native/expo-plugin",
        {
          consentCategories: ["necessary", "marketing"],
          projectUrl: "https://demo.inth.app",
        },
      ],
    ]);
    assert.equal(config.expo.ios.bundleIdentifier, "app.demo");
    assert.match(
      await readFile(path.join(expo, "inth", "privacy-app.tsx"), "utf-8"),
      /Generated by `inth mobile setup`/u
    );

    const again = setup([
      "--backend-url",
      "demo.inth.app",
      "--privacy-policy-url",
      PRIVACY,
    ]);
    assert.equal(again.status, 0, again.stdout + again.stderr);
    assert.equal(
      resultSchema.parse(JSON.parse(again.stdout)).data.skipped.length,
      2
    );

    const refused = setup([
      "--backend-url",
      "https://consent.example.com",
      "--privacy-policy-url",
      PRIVACY,
    ]);
    assert.equal(refused.status, 1);
    const { error } = errorSchema.parse(JSON.parse(refused.stdout));
    assert.equal(error.code, "usage_error");
    assert.match(
      error.message,
      /the host must be a project host under inth\.app/u
    );

    const native = path.join(parent, "native");
    await mkdir(path.join(native, "Demo.xcodeproj"), { recursive: true });
    await writeFile(path.join(native, "settings.gradle.kts"), "");
    const steps = setup(
      ["--backend-url", "demo.inth.app", "--privacy-policy-url", PRIVACY],
      native
    );
    assert.equal(steps.status, 0, steps.stdout + steps.stderr);
    const nativePlan = resultSchema.parse(JSON.parse(steps.stdout)).data;
    assert.deepEqual(nativePlan.platforms, ["ios", "android"]);
    assert.deepEqual(nativePlan.files, []);
    assert.match(
      nativePlan.steps.join("\n"),
      /backendURL: "https:\/\/demo\.inth\.app"/u
    );

    assert.deepEqual(await readdir(path.join(parent, "mobile-home")), [
      "unavailable",
    ]);
  } finally {
    await rm(parent, { force: true, recursive: true });
  }
};
